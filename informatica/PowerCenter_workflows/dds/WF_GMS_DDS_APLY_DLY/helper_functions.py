_persistent_state = {}


def load_persistent_state(state_file='persistent_state.json'):
    """Load persistent variable state from JSON file."""
    import json
    global _persistent_state
    if os.path.exists(state_file):
        try:
            with open(state_file, 'r') as f:
                _persistent_state = json.load(f)
            logger.info(f'Loaded persistent state from {state_file} ({len(_persistent_state)} scopes)')
        except Exception as e:
            logger.warning(f'Could not load persistent state from {state_file}: {e}')
            _persistent_state = {}
    else:
        logger.info(f'No persistent state file found at {state_file} — starting fresh')
        _persistent_state = {}
    return _persistent_state


def save_persistent_state(state_file='persistent_state.json'):
    """Save persistent variable state to JSON file."""
    import json
    try:
        with open(state_file, 'w') as f:
            json.dump(_persistent_state, f, indent=2, default=str)
        logger.info(f'Saved persistent state to {state_file}')
    except Exception as e:
        logger.warning(f'Could not save persistent state to {state_file}: {e}')


def get_persistent_variable(scope, var_name, default=None):
    """Get a persistent variable value from state."""
    scope_state = _persistent_state.get(scope, {})
    return scope_state.get(var_name, default)


def set_persistent_variable(scope, var_name, value):
    """Set a persistent variable value in state."""
    if scope not in _persistent_state:
        _persistent_state[scope] = {}
    _persistent_state[scope][var_name] = value
    return value


