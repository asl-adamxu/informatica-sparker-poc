def write_with_update_strategy(config, df, table_name, connection_name='default', key_columns=None, schema=None):
    """
    Write DataFrame to database using row-level update strategy.
    Expects a '_update_strategy' column with values: INSERT, UPDATE, DELETE, REJECT.
    key_columns: list of primary key columns for UPDATE/DELETE operations.
    """
    if '_update_strategy' not in df.columns:
        logger.warning('No _update_strategy column found — falling back to bulk INSERT')
        write_to_db(config, df, table_name, connection_name, schema=schema)
        return

    conn = get_db_connection(config, connection_name)
    conn_config = config.get('connections', {}).get(connection_name, {})
    if schema is None:
        schema = conn_config.get('schema', 'dbo')
    qualified_table = f'{schema}.{table_name}' if schema else table_name

    data_cols = [c for c in df.columns if c != '_update_strategy']
    if key_columns is None:
        key_columns = data_cols[:1]
        logger.warning(f'No key columns specified for update strategy — using first column: {key_columns}')

    db_type = conn_config.get('type', 'mssql')
    ph = '?' if db_type == 'mssql' else '%s'

    try:
        cursor = conn.cursor()

        df_insert = df[df['_update_strategy'] == 'INSERT']
        df_update = df[df['_update_strategy'] == 'UPDATE']
        df_delete = df[df['_update_strategy'] == 'DELETE']
        df_reject = df[df['_update_strategy'] == 'REJECT']

        if len(df_reject) > 0:
            logger.warning(f'Rejecting {len(df_reject)} rows for target {table_name}')

        if len(df_insert) > 0:
            logger.info(f'Inserting {len(df_insert)} rows into {qualified_table}')
            df_insert[data_cols].to_sql(table_name, conn, schema=schema, if_exists='append', index=False)

        if len(df_update) > 0:
            non_key_cols = [c for c in data_cols if c not in key_columns]
            set_clause = ', '.join(f'{c} = {ph}' for c in non_key_cols)
            where_clause = ' AND '.join(f'{c} = {ph}' for c in key_columns)
            update_sql = f'UPDATE {qualified_table} SET {set_clause} WHERE {where_clause}'
            logger.info(f'Updating {len(df_update)} rows in {qualified_table}')
            for _, row in df_update.iterrows():
                values = [row[c] for c in non_key_cols] + [row[c] for c in key_columns]
                cursor.execute(update_sql, values)

        if len(df_delete) > 0:
            where_clause = ' AND '.join(f'{c} = {ph}' for c in key_columns)
            delete_sql = f'DELETE FROM {qualified_table} WHERE {where_clause}'
            logger.info(f'Deleting {len(df_delete)} rows from {qualified_table}')
            for _, row in df_delete.iterrows():
                values = [row[c] for c in key_columns]
                cursor.execute(delete_sql, values)

        conn.commit()
        total = len(df_insert) + len(df_update) + len(df_delete)
        logger.info(f'Update strategy complete for {qualified_table}: {len(df_insert)} inserts, {len(df_update)} updates, {len(df_delete)} deletes, {len(df_reject)} rejects')

    except Exception as e:
        logger.error(f'Update strategy write error for {qualified_table}: {e}')
        conn.rollback()
        raise
    finally:
        conn.close()


