_lookup_cache = {}


def lookup_func(table, condition, *fields, config=None, connection_name='default'):
    """
    Informatica unconnected LOOKUP function.
    Loads and caches the lookup table, then filters by condition.
    Returns the first matching value of the first return field, or None.
    """
    global _lookup_cache
    if table not in _lookup_cache:
        if config is not None:
            try:
                lkp_conn = connection_name
                conns = config.get('connections', {})
                for cname, cval in conns.items():
                    if isinstance(cval, dict) and cval.get('connection_name', '') == table:
                        lkp_conn = cname
                        break
                df_lkp = read_from_db(config, f'SELECT * FROM {table}', lkp_conn)
                _lookup_cache[table] = df_lkp
                logger.info(f'Cached lookup table {table}: {len(df_lkp)} rows')
            except Exception as e:
                logger.warning(f'Could not load lookup table {table}: {e}')
                _lookup_cache[table] = None
        else:
            logger.warning(f'LOOKUP called for {table} without config - returning None')
            return None
    df_lkp = _lookup_cache.get(table)
    if df_lkp is None or df_lkp.empty:
        return None
    try:
        if callable(condition):
            matches = df_lkp[condition(df_lkp)]
        elif isinstance(condition, str) and '=' in condition:
            col, _, val = condition.partition('=')
            col = col.strip()
            val = val.strip().strip("'")
            if col in df_lkp.columns:
                matches = df_lkp[df_lkp[col].astype(str) == str(val)]
            else:
                return None
        else:
            return None
        if matches.empty:
            return None
        if fields:
            field = str(fields[0]).strip()
            if field in matches.columns:
                return matches.iloc[0][field]
        return matches.iloc[0].to_dict()
    except Exception as e:
        logger.warning(f'LOOKUP error on {table}: {e}')
        return None


