def parse_param_file(param_path):
    """
    Parse an Informatica .param file into a flat dict of variable names to values.
    Supports standard Informatica parameter file format:
      [Global]
      $$VAR_NAME=value
      [folder_name.WF:workflow_name.ST:session_name]
      $$CONN_NAME=value
    """
