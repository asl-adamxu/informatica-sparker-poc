def _read_xml_to_pandas(file_path, file_config):
    """Parse XML file into a pandas DataFrame."""
    import xml.etree.ElementTree as ET
    nested = file_config.get('nested', False)
    row_tag = file_config.get('row_tag', None)
    tree = ET.parse(file_path)
    root = tree.getroot()
    if row_tag:
        rows = root.findall(f'.//{row_tag}')
    else:
        rows = list(root)
    records = []
    for row in rows:
        record = dict(row.attrib)
        for child in row:
            tag = child.tag.split('}')[-1] if '}' in child.tag else child.tag
            if nested and len(child) > 0:
                record[tag] = ET.tostring(child, encoding='unicode')
            else:
                record[tag] = child.text
        records.append(record)
    return pd.DataFrame(records)


