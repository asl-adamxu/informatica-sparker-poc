def call_stored_procedure(config, proc_name, params=None, connection_name='default', output_params=None):
    """
    Execute a stored procedure and return results.
    params: dict of {param_name: value} for input parameters
    output_params: list of output parameter names to capture
    Returns: (result_df, output_values) where output_values is a dict
    """
    if params is None:
        params = {}
    if output_params is None:
        output_params = []

    conn = get_db_connection(config, connection_name)
    conn_config = config.get('connections', {}).get(connection_name, {})
    db_type = conn_config.get('type', 'mssql')

    try:
        cursor = conn.cursor()
        logger.info(f'Calling stored procedure: {proc_name} with params: {params}')

        if db_type == 'oracle':
            param_list = list(params.values())
            for out_p in output_params:
                import cx_Oracle
                param_list.append(cursor.var(cx_Oracle.STRING))
            result = cursor.callproc(proc_name, param_list)
            out_values = {}
            for i, out_p in enumerate(output_params):
                out_values[out_p] = result[len(params) + i].getvalue()
        elif db_type == 'mssql':
            param_placeholders = ', '.join(['?'] * len(params))
            if output_params:
                out_decl = '; '.join(f'@{p} OUTPUT' for p in output_params)
                sql = f'EXEC {proc_name} {param_placeholders}'
                if out_decl:
                    sql += f', {out_decl}'
            else:
                sql = f'EXEC {proc_name} {param_placeholders}'
            cursor.execute(sql, list(params.values()))
            out_values = {}
        else:
            param_placeholders = ', '.join(['%s'] * len(params))
            cursor.execute(f'CALL {proc_name}({param_placeholders})', list(params.values()))
            out_values = {}

        try:
            columns = [desc[0] for desc in cursor.description] if cursor.description else []
            rows = cursor.fetchall()
            result_df = pd.DataFrame(rows, columns=columns) if columns else pd.DataFrame()
        except Exception:
            result_df = pd.DataFrame()

        conn.commit()
        logger.info(f'Stored procedure {proc_name} returned {len(result_df)} rows')
        return result_df, out_values

    except Exception as e:
        logger.error(f'Stored procedure {proc_name} failed: {e}')
        conn.rollback()
        raise
    finally:
        conn.close()


